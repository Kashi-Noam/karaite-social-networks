doc = docx.Document(SRC)
paras = doc.paragraphs


def find(snippet, start=0):
    """Index of the first paragraph whose text contains `snippet`."""
    for i in range(start, len(doc.paragraphs)):
        if snippet in doc.paragraphs[i].text:
            return i
    raise KeyError(snippet)


def body_pPr():
    """A pPr taken from an ordinary justified body paragraph."""
    src = doc.paragraphs[find("ביום חמישי")]
    return copy.deepcopy(src._p.find(qn("w:pPr")))


def caption_pPr():
    src = doc.paragraphs[find("איור 4. תשעת הרכיבים")]
    return copy.deepcopy(src._p.find(qn("w:pPr")))


def heading_pPr():
    src = doc.paragraphs[find("מתודולוגיה")]
    return copy.deepcopy(src._p.find(qn("w:pPr")))


BODY_PPR = body_pPr()
CAP_PPR = caption_pPr()
HEAD_PPR = heading_pPr()
HEAD_RPR = copy.deepcopy(doc.paragraphs[find("מתודולוגיה")].runs[0]._r.find(qn("w:rPr")))
CAP_RPR = copy.deepcopy(doc.paragraphs[find("איור 4. תשעת הרכיבים")].runs[0]._r.find(qn("w:rPr")))
BODY_RPR = copy.deepcopy(doc.paragraphs[find("ביום חמישי")].runs[0]._r.find(qn("w:rPr")))


def make_p(pPr, chunks, rPr):
    """chunks: list of (text, bold, latin)."""
    p = OxmlElement("w:p")
    p.append(copy.deepcopy(pPr))
    for text, bold, latin in chunks:
        r = OxmlElement("w:r")
        rpr = copy.deepcopy(rPr)
        if rpr is None:
            rpr = OxmlElement("w:rPr")
        # drop any inherited bold/rtl, then set what we want
        for tag in ("w:b", "w:bCs", "w:rtl"):
            for el in rpr.findall(qn(tag)):
                rpr.remove(el)
        if bold:
            for tag in ("w:b", "w:bCs"):
                rpr.append(OxmlElement(tag))
        if not latin:
            rpr.append(OxmlElement("w:rtl"))
        r.append(rpr)
        t = OxmlElement("w:t")
        t.set(qn("xml:space"), "preserve")
        t.text = text
        r.append(t)
        p.append(r)
    return p


def parse(md):
    """*bold* and `latin` markers inside a Hebrew paragraph."""
    out, buf, i = [], "", 0
    while i < len(md):
        c = md[i]
        if c in "*`":
            j = md.find(c, i + 1)
            if j > 0:
                if buf:
                    out.append((buf, False, False)); buf = ""
                out.append((md[i + 1:j], c == "*", c == "`"))
                i = j + 1
                continue
        buf += c
        i += 1
    if buf:
        out.append((buf, False, False))
    return out


inserted = []


def after(anchor_idx, blocks):
    """blocks: list of ('p'|'h'|'c'|'img', payload). Inserted in order."""
    node = doc.paragraphs[anchor_idx]._p
    for kind, payload in blocks:
        if kind == "img":
            fname, width_in = payload
            newp = OxmlElement("w:p")
            pPr = OxmlElement("w:pPr")
            jc = OxmlElement("w:jc"); jc.set(qn("w:val"), "center")
            pPr.append(jc)
            newp.append(pPr)
            node.addnext(newp)
            node = newp
            para = docx.text.paragraph.Paragraph(newp, doc.paragraphs[anchor_idx]._parent)
            run = para.add_run()
            run.add_picture(os.path.join(FIGDIR, fname), width=Inches(width_in))
        else:
            pPr = {"p": BODY_PPR, "h": HEAD_PPR, "c": CAP_PPR}[kind]
            rPr = {"p": BODY_RPR, "h": HEAD_RPR, "c": CAP_RPR}[kind]
            newp = make_p(pPr, parse(payload), rPr)
            node.addnext(newp)
            node = newp
        inserted.append(node)


def replace_text(idx, md, rPr=None):
    """Replace a paragraph's runs, keeping its own pPr."""
    p = doc.paragraphs[idx]._p
    pPr = p.find(qn("w:pPr"))
    base = rPr if rPr is not None else copy.deepcopy(
        doc.paragraphs[idx].runs[0]._r.find(qn("w:rPr"))) if doc.paragraphs[idx].runs else BODY_RPR
    for child in list(p):
        if child is not pPr:
            p.remove(child)
    for text, bold, latin in parse(md):
        r = OxmlElement("w:r")
        rpr = copy.deepcopy(base) if base is not None else OxmlElement("w:rPr")
        for tag in ("w:b", "w:bCs", "w:rtl"):
            for el in rpr.findall(qn(tag)):
                rpr.remove(el)
        if bold:
            for tag in ("w:b", "w:bCs"):
                rpr.append(OxmlElement(tag))
        if not latin:
            rpr.append(OxmlElement("w:rtl"))
        r.append(rpr)
        t = OxmlElement("w:t")
        t.set(qn("xml:space"), "preserve")
        t.text = text
        r.append(t)
        p.append(r)


def swap_image(para_idx, fname, width_in):
    """Point an existing inline image at a new file and resize it."""
    para = doc.paragraphs[para_idx]
    for child in list(para._p):
        if child.tag != qn("w:pPr"):
            para._p.remove(child)
    run = para.add_run()
    run.add_picture(os.path.join(FIGDIR, fname), width=Inches(width_in))


def a4_portrait(para_idx):
    """Normalise the oriented one-figure section back to A4 portrait."""
    sect = doc.paragraphs[para_idx]._p.find(qn("w:pPr") + "/" + qn("w:sectPr"))
    if sect is None:
        return False
    pg = sect.find(qn("w:pgSz"))
    pg.set(qn("w:w"), "11906"); pg.set(qn("w:h"), "16838")
    if pg.get(qn("w:orient")):
        del pg.attrib[qn("w:orient")]
    mar = sect.find(qn("w:pgMar"))
    if mar is not None:
        mar.set(qn("w:top"), "1200"); mar.set(qn("w:bottom"), "1200")
        mar.set(qn("w:left"), "1300"); mar.set(qn("w:right"), "1300")
    return True


